import subprocess
result = subprocess.run(["git", "ls-files"], capture_output=True, text=True)
files = result.stdout.split("\n")
node_files = [f for f in files if "node_modules" in f]
print("Total tracked files:", len(files))
print("node_modules files:", len(node_files))
print("Sample node_modules paths:")
for f in node_files[:5]:
    print(" -", f)